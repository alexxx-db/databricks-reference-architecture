PAINTED = re.compile(r"<(path|circle|ellipse|polygon|rect)\b([^>]*?)(/?)>")


def thicken_strokes(body, scale):
    def sub(m):
        return 'stroke-width="%g"' % max(float(m.group(1)), STROKE_FLOOR / scale)

    return re.sub(r'stroke-width="([0-9.]+)"', sub, body)


STROKE_OFF = re.compile(r'stroke="none"|stroke:\s*none')


def add_outline(body, width=OUTLINE):
    """Outline every filled shape in its own colour, in place of no stroke.

    A shape that already strokes is left alone, that one is thicken_strokes'
    job. A shape that says `stroke:none` in a style attribute has to be
    rewritten rather than given a stroke attribute, because the style wins over
    presentation attributes and the outline would never paint.
    """
    decls = ('stroke:currentColor;stroke-width:%g;vector-effect:non-scaling-stroke;'
             'stroke-linejoin:round' % width)
    attrs_form = (' stroke="currentColor" stroke-width="%g"'
                  ' vector-effect="non-scaling-stroke" stroke-linejoin="round"' % width)

    def sub(m):
        tag, attrs, close = m.group(0), m.group(2), m.group(3)
        if 'fill="currentColor"' not in attrs and "fill:currentColor" not in attrs:
            return tag
        off = STROKE_OFF.search(attrs)
        if off:
            attrs = attrs[:off.start()] + decls + attrs[off.end():]
        elif "stroke=" in attrs or "stroke:" in attrs:
            return tag
        else:
            attrs += attrs_form
        return "<%s%s%s>" % (m.group(1), attrs, close)

    return PAINTED.sub(sub, body)


def namespace_ids(body, key):
    ids = set(re.findall(r'\bid="([^"]+)"', body))
    for i in sorted(ids, key=len, reverse=True):
        safe = "%s-%s" % (key, i)
        body = body.replace('id="%s"' % i, 'id="%s"' % safe)
        body = body.replace("url(#%s)" % i, "url(#%s)" % safe)
        body = body.replace('href="#%s"' % i, 'href="#%s"' % safe)
    return body


def parse_svg(name, raw):
    m = re.search(r"<svg\b([^>]*)>(.*)</svg>", raw, flags=re.S)
    if not m:
        raise ValueError("%s: no <svg> root" % name)
    head, body = m.group(1), m.group(2)
    vb = re.search(r'viewBox="([\d.\-\s,]+)"', head)
    if vb:
        x, y, w, h = [float(v) for v in re.split(r"[\s,]+", vb.group(1).strip())]
    else:
        w = float(re.search(r'width="([\d.]+)', head).group(1))
        h = float(re.search(r'height="([\d.]+)', head).group(1))
        x = y = 0.0
    if w <= 0 or h <= 0:
        raise ValueError("%s: bad viewBox" % name)
    return head, body, (x, y, w, h)


def strip_meta(body):
    body = re.sub(r"<title>.*?</title>", "", body, flags=re.S)
    body = re.sub(r"<desc>.*?</desc>", "", body, flags=re.S)
    return re.sub(r"<!--.*?-->", "", body, flags=re.S)


def fmt_num(v):
    return ("%.4f" % v).rstrip("0").rstrip(".") or "0"


def compact(body):
    body = shrink_numbers(body)
    body = re.sub(r">\s+<", "><", body)
    return re.sub(r"\s{2,}", " ", body).strip()


def place(body, box, s, pad, attrs=""):
    x, y, w, h = box
    inner = CANVAS - 2 * pad
    tx = pad + (inner - w * s) / 2.0 - x * s
    ty = pad + (inner - h * s) / 2.0 - y * s
    return compact('<g transform="translate(%s %s) scale(%s)"%s>%s</g>' % (fmt_num(tx), fmt_num(ty), fmt_num(s), attrs, body.strip()))


FILTER_USE = re.compile(r'\sfilter="url\(#[^)]*\)"')
FILTER_DEF = re.compile(r"<filter\b.*?</filter>", re.S)
SHAPE = re.compile(r"<(?:path|rect|circle|ellipse|polygon)\b[^>]*/>")


def light_fill(tag):
    col = re.search(r'fill="([^"]+)"', tag)
    return bool(col) and bool(COLOUR.fullmatch(col.group(1).strip())) and is_plate(col.group(1).strip())


def attr_num(attrs, name):
    m = re.search(r'\b%s="([\d.\-]+)"' % name, attrs)
    return float(m.group(1)) if m else 0.0


def uncontain(name, body):
    boxes, cuts = [], []

    def take(t):
        if light_fill(t.group(0)):
            cuts.append(re.sub(r'fill="[^"]+"', 'fill="#000"', t.group(0)))
            return ""
        return t.group(0)

    def lift(text):
        m = re.search(r"<rect\b([^>]*)/>", text)
        if not m or not light_fill(m.group(0)):
            raise ValueError("%s: the first rect is not a light container" % name)
        boxes.append(tuple(attr_num(m.group(1), k) for k in ("x", "y", "width", "height")))
        return SHAPE.sub(take, text[:m.start()] + text[m.end():])

    body = outside_protected(FILTER_DEF.sub("", FILTER_USE.sub("", body)), lift)
    return body, boxes[0], cuts


def knock_out(body, cuts, box, key):
    mid = key + "-ko"
    geo = 'x="%s" y="%s" width="%s" height="%s"' % tuple(fmt_num(v) for v in box)
    return ('<mask id="%s" maskUnits="userSpaceOnUse" %s><rect %s fill="#fff"/>%s</mask><g mask="url(#%s)">%s</g>'
            % (mid, geo, geo, "".join(cuts), mid, body))


def transform(name, raw):
    key = slug(name)
    head, body, box = parse_svg(name, raw)
    cuts = []
    if name in CONTAINERS:
        body, box, cuts = uncontain(name, body)
    x, y, w, h = box

    body = strip_meta(body)
    body = strip_plates(body)
    body = tone_map(body)
    body = namespace_ids(body, key)

    inner = CANVAS - 2 * PAD
    s = min(inner / w, inner / h)

    body = thicken_strokes(body, s)
    if name in HAIRLINE:
        body = add_outline(body)
    if cuts:
        body = knock_out(body, cuts, box, key)
    return place(body, box, s, PAD)


STYLE_BLOCK = re.compile(r"<style\b[^>]*>(.*?)</style>", re.S)
UNSAFE = re.compile(r"<(?:image|script|foreignObject)\b|\bhref=\"(?:https?:|data:|javascript:)|\son[a-z]+=", re.I)
ROOT_PAINT = re.compile(r'\b(fill|stroke-width|stroke-linecap|stroke-linejoin|stroke|fill-rule|clip-rule|opacity)="([^"]*)"')


def inline_styles(name, body):
    rules = {}
    for css in STYLE_BLOCK.findall(body):
        css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
        for sel, decl in re.findall(r"([^{}]+)\{([^}]*)\}", css):
            for s in sel.split(","):
                s = s.strip()
                if not re.fullmatch(r"\.[\w-]+", s):
                    raise ValueError("%s: style rule '%s' is not a single class, inline it by hand" % (name, s))
                rules.setdefault(s[1:], []).append(decl.strip().strip(";"))
    body = STYLE_BLOCK.sub("", body)

    def sub(m):
        tag = m.group(0)
        cls = re.search(r'\sclass="([^"]*)"', tag)
        if not cls:
            return tag
        decl = ";".join(d for c in cls.group(1).split() for d in rules.get(c, []) if d)
        tag = tag.replace(cls.group(0), "", 1)
        if not decl:
            return tag
        st = re.search(r'\sstyle="([^"]*)"', tag)
        if st:
            return tag.replace(st.group(0), ' style="%s;%s"' % (decl, st.group(1)), 1)
        return re.sub(r"^<([\w:-]+)", lambda t: '<%s style="%s"' % (t.group(1), decl), tag, count=1)

    return re.sub(r"<[\w:-]+\b[^>]*>", sub, body)


def transform_logo(key, raw):
    head, body, box = parse_svg(key, raw)
    if UNSAFE.search(body):
        raise ValueError("%s: logo carries an external reference or a script" % key)
    body = strip_meta(body).replace("xlink:href=", "href=")
    body = re.sub(r"<metadata\b.*?</metadata>", "", body, flags=re.S)
    body = re.sub(r"<sodipodi:namedview\b[^>]*?(?:/>|>.*?</sodipodi:namedview>)", "", body, flags=re.S)
    body = inline_styles(key, body)
    body = FILTER_DEF.sub("", FILTER_USE.sub("", body))
    body = namespace_ids(body, "lg-" + key)
    attrs = "".join(' %s="%s"' % m for m in ROOT_PAINT.findall(head))
    return body, box, attrs


def service_logo(key, raw):
    body, box, attrs = transform_logo(key, raw)
    inner = CANVAS - 2 * LOGO_PAD
    return place(body, box, min(inner / box[2], inner / box[3]), LOGO_PAD, attrs)


def provider_logo(key, raw):
    body, box, attrs = transform_logo(key, raw)
    return {"vb": " ".join(fmt_num(v) for v in box), "g": compact("<g%s>%s</g>" % (attrs, body))}


def art_key(member):
    k = slug(os.path.splitext(os.path.basename(member))[0])
    k = re.sub(r"^(?:arch|res|\d+-icon-service)-", "", k)
    return re.sub(r"-(?:48|64|512)(?:-color(?:-rgb)?|-item)?$|-(?:48-color|scalable|color-icon)$", "", k)


def build_logos(refresh=False):
    providers = {k: provider_logo(k, fetch(k, src, refresh)) for k, src in sorted(CLOUD_LOGOS.items())}
    bundles = {}
    for cloud, tiles in sorted(SERVICES.items()):
        art, src, names = {}, {}, {}
        for tile, (pkg, member) in sorted(tiles.items()):
            key = art_key(member)
            if key not in art:
                art[key] = service_logo(key, fetch_pkg(pkg, member, refresh))
                src[key] = PACKAGES[pkg][1]
            names[tile] = key
        bundles[cloud] = {"tiles": names, "art": art, "src": src}
    return providers, bundles


def render_logos(providers):
    lines = [LOGOS_BEGIN, "const CLOUD_LOGOS = {"]
    for k in sorted(providers):
        lines.append('  "%s": %s,' % (k, json.dumps(providers[k], sort_keys=True)))
    lines.append("};")
    lines.append(LOGOS_END)
    return "\n".join(lines)


def bundle_text(bundle):
    return json.dumps(bundle, sort_keys=True, ensure_ascii=False, separators=(",", ":")) + "\n"


GEOM_ATTR = re.compile(r'\b(d|cx|cy|r|rx|ry|x|y|x1|y1|x2|y2|width|height|points)="([^"]*)"')


def shrink_numbers(body, places=2):
    """Round geometry to `places`. On a 48px canvas this stays far below one pixel."""
    def rounded(m):
        out = (("%." + str(places) + "f") % float(m.group(1))).rstrip("0").rstrip(".") or "0"
        return out + (" " if m.group(2) and "." not in out else "")

    def round_all(text):
        return re.sub(r"(?<![\d.])(-?\d+\.\d+)(?=(\.)?)", rounded, text)

    return GEOM_ATTR.sub(lambda m: '%s="%s"' % (m.group(1), round_all(m.group(2))), body)


def build(refresh=False):
    out = {}
    for name, url in sorted(MARKS.items()):
        out[name] = transform(name, fetch(name, url, refresh))
    return out


def render(marks):
    lines = [BEGIN, "const PRODUCT_MARKS = {"]
    for name in sorted(marks):
        body = marks[name].replace("\\", "\\\\").replace('"', '\\"')
        lines.append('  "%s": "%s",' % (name, body))
    lines.append("};")
    lines.append(END)
    return "\n".join(lines)


CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"


def measure(marks, px=19):
    """Ink coverage per mark at canvas size, so HAIRLINE is evidence, not taste.

    Renders every mark into one strip of `px`-wide cells and reads the mean
    darkness of each cell back out. Needs Chrome and Pillow, which is why it is
    a separate mode and not part of the build.
    """
    import subprocess
    import tempfile
    from PIL import Image

    names = sorted(marks)
    cells = "".join('<i><svg viewBox="0 0 48 48" fill=none>%s</svg></i>' % marks[n] for n in names)
    page = ("<!doctype html><meta charset=utf-8><style>html,body{margin:0;background:#fff}"
            "#g{display:grid;grid-template-columns:repeat(%d,%dpx);width:max-content}"
            "i{display:block;width:%dpx;height:%dpx;line-height:0}"
            "svg{width:%dpx;height:%dpx;color:#000;display:block}</style>"
            "<div id=g>%s</div>" % (len(names), px, px, px, px, px, cells))

    with tempfile.TemporaryDirectory() as tmp:
        src = pathlib.Path(tmp) / "strip.html"
        shot = pathlib.Path(tmp) / "strip.png"
        src.write_text(page)
        subprocess.run(
            [CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars",
             "--force-device-scale-factor=1",
             "--window-size=%d,%d" % (len(names) * px + 20, px + 20),
             "--virtual-time-budget=5000", "--screenshot=%s" % shot, src.as_uri()],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
        img = Image.open(shot).convert("L")
        out = {}
        for i, name in enumerate(names):
            px_vals = list(img.crop((i * px, 0, (i + 1) * px, px)).getdata())
            out[name] = sum(255 - v for v in px_vals) / (255.0 * len(px_vals))
    return out


def block_pattern(begin, end):
    return re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)


def orphaned_keys(html):
    """MARKS is keyed by tile name, so a rename would silently drop the mark."""
    for begin, end in ((BEGIN, END), (LOGOS_BEGIN, LOGOS_END)):
        html = block_pattern(begin, end).sub("", html)
    tiles = set(re.findall(r'\bn:"([^"]+)"', html))
    wanted = list(MARKS) + [n for c in SERVICES.values() for n in c]
    return sorted(name for name in set(wanted) if name not in tiles)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--refresh", action="store_true")
    ap.add_argument("--measure", action="store_true")
    args = ap.parse_args()

    try:
        marks = build(args.refresh)
        providers, bundles = ({}, {}) if args.measure else build_logos(args.refresh)
    except (RuntimeError, ValueError) as exc:
        print("FAIL: %s" % exc)
        return 1

    if args.measure:
        ink = measure(marks)
        faint = [n for n, v in ink.items() if v < INK_FLOOR]
        for name in sorted(ink, key=ink.get):
            print("%-30s %.3f%s" % (name, ink[name], "  <- under the floor" if ink[name] < INK_FLOOR else ""))
        print("\n%d of %d marks under %.2f ink at 19px" % (len(faint), len(ink), INK_FLOOR))
        return 1 if faint else 0

    html = APP.read_text()
    blocks = [(block_pattern(BEGIN, END), render(marks), "PRODUCT_MARKS"),
              (block_pattern(LOGOS_BEGIN, LOGOS_END), render_logos(providers), "CLOUD_LOGOS")]
    files = {LOGO_DIR / (cloud + ".json"): bundle_text(b) for cloud, b in bundles.items()}
    n_art = sum(len(b["art"]) for b in bundles.values())

    if args.check:
        fails = []
        for pat, block, label in blocks:
            found = pat.search(html)
            if not found:
                fails.append("%s block missing from app/index.html" % label)
            elif found.group(0) != block:
                fails.append("embedded %s differs from a fresh build" % label)
        for path, text in sorted(files.items()):
            rel = path.relative_to(ROOT)
            if not path.exists() or path.read_text() != text:
                fails.append("%s differs from a fresh build" % rel)
            if len(text.encode()) > LOGO_BUDGET:
                fails.append("%s is %d bytes, over the %d byte budget" % (rel, len(text.encode()), LOGO_BUDGET))
        built = {p.name for p in files}
        fails += ["%s is no longer built" % p.relative_to(ROOT) for p in sorted(LOGO_DIR.glob("*.json")) if p.name not in built]
        fails += ["no tile carries the name '%s', its artwork can never show" % n for n in orphaned_keys(html)]
        for f in fails:
            print("FAIL: %s" % f)
        if fails:
            return 1
        print("OK: %d marks, %d cloud logos and %d service logos embedded, current, and all matched to a tile"
              % (len(MARKS), len(providers), n_art))
        return 0

    for pat, block, label in blocks:
        if not pat.search(html):
            print("FAIL: no %s block to replace, add the markers first" % label)
            return 1
        html = pat.sub(lambda _: block, html, count=1)
    APP.write_text(html)
    LOGO_DIR.mkdir(parents=True, exist_ok=True)
    for path, text in sorted(files.items()):
        path.write_text(text)
    print("wrote %d marks, %d cloud logos, %d service logos in %s" % (
        len(MARKS), len(providers), n_art, ", ".join("%s %d B" % (p.name, len(t.encode())) for p, t in sorted(files.items()))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
